public class MatrixforDemo {

    public static void main(String[] args){

        for(int i=1; i<=5;i++){//this for for always row

            for(int j=1;j<=5;j++){  //this for for column
                // System.out.print("*" +"\t");  //this will print in front of first word

                if(i==3){
                    System.out.print("$"+"\t");
                }
                else{
                System.out.print(j +"\t");
                }
            }

            System.out.println();

        }
    }  
}

                                                                                                                                



